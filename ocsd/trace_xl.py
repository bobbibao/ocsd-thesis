"""Trace one OCSD generation (final OCSD: M1-M5 on SDXL, setting "natural", M3 off) and save every intermediate.

The image is generated by exactly the code and settings of the locked paper run (assets/xl_paper_v1, arm
`ocsd_xl_natural`, round c1): `make_objects` (M2) then `run_arm` (M4 + M5). Nothing in the computation is changed;
light wrappers only record what passes through:
  M1  the parsed scene: per-object sketches, masks, boxes, relations, grouped prompt
  M2  the K candidates of every object, the Grounding DINO box and SAM mask of each, the selected candidate
  M4  the composed foreground, the placed masks, the anchor masks of the latent-blending phase
  M5  (a) cross-attention map of every object at a few steps, (b) energy per step, (c) the scene ControlNet input,
      the latent the U-Net sees at every step (decoded) and the clean-image prediction x0 at every step,
      (d) the post-generation check (detections, matches) and, when it runs, the repair region and its steps
Output: <drive>/trace_ocsd/<sid>_s<seed>/ (PNG/JPG per module, trace.json, overview sheets, one ZIP).
The final image is compared with the image of the paper run on Drive when that exists (same code, same seed).
"""
