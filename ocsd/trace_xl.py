ARM = "ocsd_xl_natural"
PROTOCOL = "xl_paper_v1"
DEFAULT_SID = "qd_3_medium_003"     # "an orange bus, a wooden bench and an orange bus near a train station" (slides)
ATTN_STEPS = (0, 3, 6, 10, 15, 22, 29)
PALETTE = [(230, 97, 1), (46, 90, 156), (60, 150, 80), (160, 60, 160), (200, 160, 0), (0, 150, 160), (200, 40, 60),
           (120, 90, 40), (90, 90, 90), (240, 120, 160)]


# ---------------------------------------------------------------------------------------------- small image helpers
def _w(path: Path, img: np.ndarray, size: int | None = 512):
    path.parent.mkdir(parents=True, exist_ok=True)
    if img.dtype != np.uint8:
        img = np.clip(img, 0, 255).astype(np.uint8)
    if img.ndim == 2:
        img = np.repeat(img[..., None], 3, 2)
    if size and img.shape[0] != size:
        img = cv2.resize(img, (size, size), interpolation=cv2.INTER_AREA if img.shape[0] > size else cv2.INTER_NEAREST)
    ext = path.suffix.lower()
    cv2.imwrite(str(path), cv2.cvtColor(img, cv2.COLOR_RGB2BGR), [cv2.IMWRITE_JPEG_QUALITY, 92] if ext == ".jpg" else [])
    return str(path)


def _boxes(img: np.ndarray, boxes, labels, colors, width: int = 3) -> np.ndarray:
    out = img.copy()
    f = out.shape[0] / 512
    for b, lab, c in zip(boxes, labels, colors):
        x0, y0, x1, y1 = [int(round(v)) for v in b]
        cv2.rectangle(out, (x0, y0), (x1, y1), c, max(1, int(width * f)))
        if lab:
            cv2.putText(out, lab, (x0 + 3, max(y0 + int(16 * f), int(14 * f))), cv2.FONT_HERSHEY_SIMPLEX, 0.5 * f, c,
                        max(1, int(1.5 * f)), cv2.LINE_AA)
    return out


def _tint(img: np.ndarray, mask: np.ndarray, color, a: float = 0.45) -> np.ndarray:
    out = img.astype(np.float32)
    m = mask.astype(bool)
    out[m] = out[m] * (1 - a) + np.array(color, np.float32) * a
    return out.clip(0, 255).astype(np.uint8)


def _heat(base: np.ndarray, amap: np.ndarray) -> np.ndarray:
    a = amap.astype(np.float32)
    a = (a - a.min()) / (a.max() - a.min() + 1e-8)
    a = cv2.resize(a, base.shape[:2][::-1], interpolation=cv2.INTER_CUBIC).clip(0, 1)
    col = cv2.applyColorMap((a * 255).astype(np.uint8), cv2.COLORMAP_JET)[..., ::-1]
    return (base * 0.45 + col * 0.55).astype(np.uint8)


def _label(img: np.ndarray, text: str, h: int = 30) -> np.ndarray:
    bar = np.full((h, img.shape[1], 3), 255, np.uint8)
    cv2.putText(bar, text, (6, h - 9), cv2.FONT_HERSHEY_SIMPLEX, 0.55, (31, 36, 48), 1, cv2.LINE_AA)
    return np.concatenate([bar, img], 0)


def _sheet(rows, tile: int = 256, gap: int = 6) -> np.ndarray:
    """rows: list of (row title, [(caption, image), ...])."""
    ncol = max(len(r[1]) for r in rows)
    W = 180 + ncol * (tile + gap)
    out = []
    for title, items in rows:
        cells = [np.full((tile + 30, 180, 3), 255, np.uint8)]
        cv2.putText(cells[0], title, (6, tile // 2 + 20), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (217, 105, 43), 2, cv2.LINE_AA)
        for cap, im in items:
            im = np.repeat(im[..., None], 3, 2) if im.ndim == 2 else im
            im = cv2.resize(im.astype(np.uint8), (tile, tile), interpolation=cv2.INTER_AREA)
            cells += [_label(im, cap), np.full((tile + 30, gap, 3), 255, np.uint8)]
        row = np.concatenate(cells, 1)
        row = np.concatenate([row, np.full((row.shape[0], W - row.shape[1], 3), 255, np.uint8)], 1)
        out += [row, np.full((gap, W, 3), 255, np.uint8)]
    return np.concatenate(out, 0)


# ---------------------------------------------------------------------------------------------- recorder
class _Vis:
    """Delegates to the real Vision; records every Grounding DINO / SAM call with the current phase."""

    def __init__(self, vis, rec):
        self._vis, self._rec = vis, rec

    def __getattr__(self, name):
        obj = getattr(self._vis, name)
        if name == "gdino":
            def gdino(img, classes, *a, **k):
                dets = obj(img, classes, *a, **k)
                self._rec.calls.append(dict(kind="gdino", phase=self._rec.phase, img=img, classes=list(classes),
                                            dets=[dict(d) for d in dets], thr=k.get("thr")))
                return dets
            return gdino
        if name == "sam":
            def sam(img, box):
                m = obj(img, box)
                self._rec.calls.append(dict(kind="sam", phase=self._rec.phase, box=list(map(float, box)), mask=m))
                return m
            return sam
        return obj


class Recorder:
    def __init__(self, eng):
        self.eng = eng
        self.phase = None
        self.calls = []             # gdino / sam calls
        self.samples = []           # M2: (prompts, seeds, images)
        self.steps = []             # per U-Net step: phase, idx, t, z_in (cpu), x0 (cpu), attn maps
        self.energy = []            # (phase, step, E)
        self.ctx = {}               # phase -> SceneCond
        self.anchors = []
        self.fg = None
        self.repair_out = []
        self._n = {}

    def install(self):
        from . import method
        eng, rec = self.eng, self
        self._orig = dict(sample=method.sample, build_scene=method.build_scene, repair_scene=method.repair_scene,
                          scene_cond=method.scene_cond, anchor_masks=method.anchor_masks,
                          compose_foreground=method.compose_foreground)
        o = self._orig

        def sample(eng_, prompts, seeds, *a, **k):
            imgs = o["sample"](eng_, prompts, seeds, *a, **k)
            if rec.phase == "m2":
                rec.samples.append(dict(prompts=list(prompts), seeds=list(seeds), imgs=[np.asarray(i) for i in imgs]))
            return imgs

        def build_scene(*a, **k):
            rec.phase, rec._n["scene"] = "scene", 0
            try:
                return o["build_scene"](*a, **k)
            finally:
                rec.phase = "verify"

        def repair_scene(*a, **k):
            r = sum(1 for p in rec._n if p.startswith("repair")) + 1
            rec.phase = f"repair{r}"
            rec._n[rec.phase] = 0
            try:
                out = o["repair_scene"](*a, **k)
                rec.repair_out.append(out)
                return out
            finally:
                rec.phase = "verify"

        def scene_cond(*a, **k):
            ctx = o["scene_cond"](*a, **k)
            if rec.phase and rec.phase not in rec.ctx:
                rec.ctx[rec.phase] = ctx
            return ctx

        def anchor_masks(*a, **k):
            out = o["anchor_masks"](*a, **k)
            if rec.phase == "scene":
                rec.anchors = [m.detach().float().cpu()[0, 0].numpy() for m in out]
            return out

        def compose_foreground(*a, **k):
            out = o["compose_foreground"](*a, **k)
            rec.fg = out
            return out

        for name, fn in dict(sample=sample, build_scene=build_scene, repair_scene=repair_scene, scene_cond=scene_cond,
                             anchor_masks=anchor_masks, compose_foreground=compose_foreground).items():
            setattr(method, name, fn)

        self._cfg_eps, self._step, self._energy = eng.cfg_eps, eng.step, eng.energy_update

        def cfg_eps(z, t, emb_c, emb_u, guidance, control=None, cn_scale=0.0, *a, **k):
            ph = rec.phase
            if ph not in ("scene",) and not (ph or "").startswith("repair"):
                return rec._cfg_eps(z, t, emb_c, emb_u, guidance, control, cn_scale, *a, **k)
            idx = rec._n[ph]
            want_attn = ph == "scene" and idx in ATTN_STEPS
            if want_attn:
                ctx = rec.ctx.get(ph)
                n_pix = int(ctx.masks_lr.shape[-1] * ctx.masks_lr.shape[-2]) if ctx is not None else None
                eng.ctrl.store, eng.ctrl.store_res = True, n_pix
                eng.ctrl.reset_maps()
            eps = rec._cfg_eps(z, t, emb_c, emb_u, guidance, control, cn_scale, *a, **k)
            maps = None
            if want_attn:
                try:
                    from .attention import token_maps
                    A = eng.ctrl.aggregated_map(-1)
                    ctx = rec.ctx.get(ph)
                    if A is not None and ctx is not None:
                        n = len(ctx.region_masks)
                        maps = token_maps(A.float(), ctx.att_tokens[:n], ctx.eot).cpu().numpy()
                finally:
                    eng.ctrl.store = False
                    eng.ctrl.reset_maps()
            rec.steps.append(dict(phase=ph, idx=idx, t=int(t), z_in=z.detach().float().cpu(),
                                  eps=eps.detach().float().cpu(), attn=maps, cn_scale=float(cn_scale)))
            rec._n[ph] = idx + 1
            return eps

        def energy_update(z, t, *a, **k):
            z2, E = rec._energy(z, t, *a, **k)
            rec.energy.append(dict(phase=rec.phase, step=rec._n.get(rec.phase, -1), t=int(t), E=float(E)))
            return z2, E

        eng.cfg_eps, eng.energy_update = cfg_eps, energy_update
        return self

    def uninstall(self):
        from . import method
        for name, fn in self._orig.items():
            setattr(method, name, fn)
        for name in ("cfg_eps", "energy_update"):
            self.eng.__dict__.pop(name, None)


# ---------------------------------------------------------------------------------------------- main
def _x0(eng, z, eps, t):
    ab = eng.scheduler.alphas_cumprod[int(t)].float()
    return (z - (1 - ab).sqrt() * eps) / ab.sqrt()


def _decode(eng, z: torch.Tensor) -> np.ndarray:
    with torch.no_grad():
        return eng.to_image(z.to(eng.device, eng.dtype))[0]


def trace(drive_root: str, sid: str = DEFAULT_SID, seed: int = 0, eng=None, vis=None, out_root: str | None = None,
          log=print, scene_dir: str | None = None, size: int | None = None, overrides: dict | None = None) -> dict:
    """scene_dir / size / overrides: a local scene folder, frame size and settings for CPU tests with tiny models."""
    from . import ocsd_xl, xl_study
    from .data import load_scene
    from .matching import consistency, verify_pass
    from .sketch import sketch_to_control

    if scene_dir is None:
        p = xl_study.load_protocol(PROTOCOL, drive_root)      # sets round c1, imports the 72 paper scenes
        if sid not in p["scenes"]:
            raise ValueError(f"{sid} is not one of the 72 paper scenes")
        sdir = [d for d in xl_study.scene_dirs(p) if Path(d).name == sid][0]
    else:
        p = json.loads((xl_study.ROOT / "assets" / PROTOCOL / "protocol.json").read_text())
        ocsd_xl.use_round(p["round"])
        sdir = scene_dir
    if overrides:
        ocsd_xl.XL_COMMON.update(overrides)
    scene = load_scene(sdir)
    scene_xl = ocsd_xl.upscale_scene(scene, size or int(p.get("size", 1024)))
    out = Path(out_root or Path(drive_root) / "trace_ocsd") / f"{sid}_s{seed}"
    out.mkdir(parents=True, exist_ok=True)
    if eng is None:
        from .engine_xl import EngineXL
        eng = EngineXL.from_pretrained(cache_dir=os.environ.get("HF_HOME"), models=p["models"])
    if vis is None:
        from .vision import Vision
        vis = Vision(str(eng.device), cache_dir=os.environ.get("HF_HOME"))
    if hasattr(vis, "set_scene"):
        vis.set_scene(scene_xl)
    kind, cfg = ocsd_xl.arm_config(ARM)
    H = scene_xl.sketch.shape[0]
    log(f"[trace] {sid} seed {seed}, arm {ARM}: omega={cfg.omega}, alpha={cfg.alpha}, steps={cfg.steps}, "
        f"energy={cfg.use_energy} (eta {cfg.eta}, tau {cfg.tau}), verify={cfg.use_verify}, R={cfg.R}")

    rec = Recorder(eng).install()
    pv = _Vis(vis, rec)
    t0 = time.time()
    try:
        rec.phase = "m2"
        m2_log = {}
        objs = ocsd_xl.make_objects(eng, pv, scene_xl, seed, m2_log, ocsd_xl.arm_m2(ARM))
        rec.phase = None
        run_log = {}
        img = ocsd_xl.run_arm(ARM, eng, pv, scene_xl, seed, objs, run_log)
    finally:
        rec.uninstall()
    gen_s = time.time() - t0
    log(f"[trace] generated in {gen_s:.0f} s; writing intermediates")

    meta = dict(sid=sid, seed=seed, arm=ARM, protocol=PROTOCOL, round=ocsd_xl.ROUND, cfg=cfg.to_dict(), n_obj=scene.n,
                caption=scene.caption, bg=scene.bg, generation_seconds=gen_s, files={})
    F = meta["files"]
    n = scene_xl.n
    cols = [PALETTE[i % len(PALETTE)] for i in range(n)]
    labels = [f"{i + 1}:{o.cls}" for i, o in enumerate(scene_xl.objects)]

    # ---------------- input + M1
    sk = np.repeat(scene_xl.sketch[..., None], 3, 2)
    F["input_sketch"] = _w(out / "00_input" / "sketch.png", sk)
    parsed = sk.copy()
    for o, c in zip(scene_xl.objects, cols):
        parsed = _tint(parsed, o.mask, c, 0.35)
    parsed = _boxes(parsed, [o.box for o in scene_xl.objects], labels, cols)
    F["m1_parsed"] = _w(out / "M1" / "parsed_masks_boxes.png", parsed)
    F["m1_objects"] = []
    for i, o in enumerate(scene_xl.objects):
        F["m1_objects"].append(_w(out / "M1" / f"obj{i + 1}_{o.cls}_sketch.png", o.sketch))
    meta["m1"] = dict(objects=[dict(cls=o.cls, phrase=o.phrase, box=[round(float(v), 1) for v in o.box],
                                    mask_area=float(o.mask.mean())) for o in scene_xl.objects],
                      relations=[list(r) for r in scene_xl.relations],
                      global_prompt=run_log.get("global_prompt"))
    (out / "M1" / "prompt_and_relations.txt").write_text(
        "Caption: " + scene.caption + "\nGrouped global prompt: " + str(run_log.get("global_prompt")) + "\nRelations:\n"
        + "\n".join(f"  {labels[i]} {r} {labels[j]}" for i, j, r in scene_xl.relations))

    # ---------------- M2
    m2 = []
    m2_calls = [c for c in rec.calls if c["phase"] == "m2"]
    ci = 0
    for i, (o, s) in enumerate(zip(scene_xl.objects, rec.samples)):
        cands = []
        for k, cimg in enumerate(s["imgs"]):
            g = m2_calls[ci] if ci < len(m2_calls) and m2_calls[ci]["kind"] == "gdino" else None
            ci += 1 if g is not None else 0
            sm = m2_calls[ci] if ci < len(m2_calls) and m2_calls[ci]["kind"] == "sam" else None
            ci += 1 if sm is not None else 0
            vis_img = cimg.copy()
            if sm is not None:
                vis_img = _tint(vis_img, sm["mask"], cols[i], 0.35)
                vis_img = _boxes(vis_img, [sm["box"]], [o.cls], [cols[i]])
            chosen = bool(np.array_equal(cimg, objs[i].img))
            f = _w(out / "M2" / f"obj{i + 1}_{o.cls}_cand{k + 1}{'_SELECTED' if chosen else ''}.jpg", vis_img)
            cands.append(dict(file=f, seed=s["seeds"][k], selected=chosen,
                              gdino=[dict(box=[round(v, 1) for v in d["box"]], score=round(d["score"], 3))
                                     for d in (g["dets"] if g else [])]))
        m2.append(dict(cls=o.cls, prompt=s["prompts"][0], score=float(objs[i].score), candidates=cands,
                       sketch_crop=_w(out / "M2" / f"obj{i + 1}_{o.cls}_sketch_crop.png", objs[i].sketch_crop)))
    meta["m2"] = m2

    # ---------------- M4
    canvas, placed, m_init = rec.fg
    F["m4_foreground"] = _w(out / "M4" / "composed_foreground.jpg", canvas)
    pm = np.full((H, H, 3), 255, np.uint8)
    for m, c in zip(placed, cols):
        pm = _tint(pm, m, c, 0.8)
    F["m4_placed"] = _w(out / "M4" / "placed_object_masks.png", pm)
    k_blend = int(run_log.get("blend_steps", 0))
    for j in sorted({0, max(k_blend - 1, 0)}):
        if j < len(rec.anchors):
            F[f"m4_anchor_{j}"] = _w(out / "M4" / f"anchor_mask_step{j:02d}.png", (rec.anchors[j] * 255).astype(np.uint8))
    meta["m4"] = dict(blend_steps=k_blend, total_steps=cfg.steps, alpha=cfg.alpha, anchor_shrink=cfg.anchor_shrink)

    # ---------------- M5: scene control, denoising trajectory, attention, energy
    ctx = rec.ctx.get("scene")
    F["m5c_control"] = _w(out / "M5" / "scene_controlnet_input.png", sketch_to_control(scene_xl.sketch))
    traj = []
    for s in rec.steps:
        ph = s["phase"]
        sub = out / ("M5_denoise" if ph == "scene" else f"M5d_{ph}")
        x0 = _x0(eng, s["z_in"], s["eps"], s["t"])
        f_z = _w(sub / f"step{s['idx']:02d}_t{s['t']:03d}_unet_input.jpg", _decode(eng, s["z_in"]))
        x0_img = _decode(eng, x0)
        f_x = _w(sub / f"step{s['idx']:02d}_t{s['t']:03d}_predicted_x0.jpg", x0_img)
        row = dict(phase=ph, step=s["idx"], t=s["t"], unet_input=f_z, x0=f_x,
                   blend=ph == "scene" and s["idx"] < k_blend, scene_cn_scale=s["cn_scale"])
        if s["attn"] is not None:
            row["attn"] = []
            for i, a in enumerate(s["attn"]):
                row["attn"].append(_w(out / "M5_attention" / f"step{s['idx']:02d}_obj{i + 1}_{scene_xl.objects[i].cls}.jpg",
                                      _heat(x0_img, a)))
        traj.append(row)
    meta["m5"] = dict(trajectory=traj, energy=rec.energy, omega=cfg.omega, lambda0=cfg.lambda0, gamma=cfg.gamma,
                      region_masks=[_w(out / "M5" / f"region_obj{i + 1}.png", (m * 255).astype(np.uint8))
                                    for i, m in enumerate(ctx.region_masks)] if ctx is not None else [])

    # ---------------- M5(d) verification and repair
    checks = []
    for c in rec.calls:
        if c["kind"] != "gdino" or c["phase"] != "verify":
            continue
        cons = consistency(scene_xl, c["dets"], 0.1)      # exactly as method.generate
        im = _boxes(c["img"], [o.box for o in scene_xl.objects], [""] * n, [(170, 170, 170)] * n, 2)
        dl = [f"{d['cls']} {d['score']:.2f}" for d in c["dets"]]
        dc = [(0, 160, 0) if any(j == jd for j, _ in cons["matched"]) else (220, 30, 30) for jd in range(len(c["dets"]))]
        im = _boxes(im, [d["box"] for d in c["dets"]], dl, dc)
        f = _w(out / "M5d" / f"check{len(checks) + 1}.jpg", im)
        checks.append(dict(file=f, opr=cons["opr"], oce_c=cons["oce_c"], ra=cons["ra"], miou=cons["miou"],
                           passed=bool(verify_pass(cons)), missing=cons["missing"],
                           detections=[dict(cls=d["cls"], box=[round(v, 1) for v in d["box"]], score=round(d["score"], 3))
                                       for d in c["dets"]]))
    meta["m5d"] = dict(checks=checks, verify_log=run_log.get("verify"), repairs=run_log.get("repairs"),
                       repair_regions=[dict(missing_ids=x.get("missing_ids"), editable_area=x.get("editable_area"))
                                       for x in run_log.get("repair_regions", [])])
    F["final"] = _w(out / "final_1024.jpg", img, None)
    F["final_512"] = _w(out / "final_512.png", img)

    # ---------------- same image as the paper run?
    ref = Path(drive_root) / p["drive_root"] / "hires" / ARM / f"{sid}_s{seed}.jpg"
    if ref.exists():
        r = cv2.cvtColor(cv2.imread(str(ref)), cv2.COLOR_BGR2RGB)
        diff = float(np.abs(r.astype(np.float32) - img.astype(np.float32)).mean())
        meta["paper_run_check"] = dict(reference=str(ref), mean_abs_diff=diff, same_image=diff < 3.0)
        log(f"[trace] compared with the paper-run image: mean |diff| = {diff:.2f} (JPEG noise is about 1)")
    else:
        meta["paper_run_check"] = dict(reference=str(ref), missing=True)

    # ---------------- overview sheets
    scene_rows = [r for r in traj if r["phase"] == "scene"]
    pick = sorted({0, max(k_blend - 1, 0), k_blend, 6, 10, 15, 20, 25, len(scene_rows) - 1})
    pick = [j for j in pick if 0 <= j < len(scene_rows)]
    rd = lambda f: cv2.cvtColor(cv2.imread(f), cv2.COLOR_BGR2RGB)
    rows = [("Input / M1", [("sketch", sk), ("M1 parsed", parsed)]
             + [(labels[i], rd(f)) for i, f in enumerate(F["m1_objects"])]),
            ("M2", [(f"{labels[i]} cand{k + 1}{' *' if c['selected'] else ''}", rd(c["file"]))
                    for i, o in enumerate(m2) for k, c in enumerate(o["candidates"])][:10]),
            ("M4", [("foreground", canvas), ("placed masks", pm)]
             + [(f"anchor step {j}", rd(F[f'm4_anchor_{j}'])) for j in sorted({0, max(k_blend - 1, 0)})
                if f"m4_anchor_{j}" in F] + [("scene CN input", rd(F["m5c_control"]))]),
            ("M5 x_t", [(f"step {scene_rows[j]['step']} t={scene_rows[j]['t']}", rd(scene_rows[j]["unet_input"]))
                        for j in pick]),
            ("M5 x0-pred", [(f"step {scene_rows[j]['step']}", rd(scene_rows[j]["x0"])) for j in pick])]
    att_rows = [r for r in scene_rows if r.get("attn")]
    for i in range(n):
        rows.append((f"M5a {labels[i]}"[:16], [(f"step {r['step']}", rd(r["attn"][i])) for r in att_rows]))
    rows.append(("M5d / final", [(f"check {k + 1} {'PASS' if c['passed'] else 'FAIL'}", rd(c["file"]))
                                 for k, c in enumerate(checks)] + [("final", img)]))
    F["overview"] = _w(out / "OVERVIEW.jpg", _sheet(rows), None)
    strip = [("noise", rd(scene_rows[0]["unet_input"]))] + \
            [(f"step {scene_rows[j]['step']}", rd(scene_rows[j]["x0"])) for j in pick[1:]] + [("final", img)]
    F["strip"] = _w(out / "NOISE_TO_IMAGE.jpg", _sheet([("noise -> image", strip)]), None)

    (out / "trace.json").write_text(json.dumps(meta, indent=1, default=lambda o: o.tolist() if hasattr(o, "tolist") else str(o)))
    zpath = out.parent / f"TRACE_{sid}_s{seed}.zip"
    with ZipFile(zpath, "w", ZIP_DEFLATED) as z:
        for f in out.rglob("*"):
            if f.is_file():
                z.write(f, str(f.relative_to(out.parent)))
    meta["zip"] = str(zpath)
    log(f"[trace] wrote {out} and {zpath}")
    return meta
